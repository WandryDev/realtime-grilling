import { invoke as tauriInvoke } from "@tauri-apps/api/core";
import {
  type EventCallback,
  type EventName,
  listen as tauriListen,
  type UnlistenFn,
} from "@tauri-apps/api/event";
import { Effect, Option, Queue, Schema, Stream } from "effect";

/*
 * Bridge from the Tauri IPC to Effect. Every `layerTauri` goes through
 * these two functions:
 *
 * - `call` turns a command into an `Effect` that fails with `BackendError`;
 * - `listen` turns an event into a `Stream` that drops the listener when
 *   the stream stops (completion, failure or interruption).
 *
 * Both accept the wrappers tauri-specta generates in `src/bindings.ts`
 * (`commands.projectsList()`, `events.dataChanged`) as well as plain
 * command and event names for the raw `invoke` / `listen`.
 */

/** What a command can fail with: the Rust `CommandError` plus the IPC. */
export const BackendErrorKind = Schema.Literals([
  "NotFound",
  "Invalid",
  "Storage",
  "Transport",
]);
export type BackendErrorKind = typeof BackendErrorKind.Type;

export class BackendError extends Schema.TaggedError<BackendError>()(
  "BackendError",
  { kind: BackendErrorKind, message: Schema.String }
) {}

/** The `#[serde(tag = "kind")] CommandError` of the Rust side. */
const CommandError = Schema.Struct({
  kind: Schema.Literals(["NotFound", "Invalid", "Storage"]),
  message: Schema.String,
});
const decodeCommandError = Schema.decodeUnknownOption(CommandError);

/** Result of a command wrapper generated by tauri-specta. */
export type CommandResult<T, E = unknown> =
  | { data: T; status: "ok" }
  | { error: E; status: "error" };

function transportMessage(cause: unknown) {
  if (cause instanceof Error) {
    return cause.message;
  }
  return typeof cause === "string" ? cause : "Команда не дошла до бэкенда";
}

/** A rejected command: a `CommandError` payload, anything else is IPC. */
function toBackendError(cause: unknown) {
  return Option.match(decodeCommandError(cause), {
    onNone: () =>
      new BackendError({ kind: "Transport", message: transportMessage(cause) }),
    onSome: ({ kind, message }) => new BackendError({ kind, message }),
  });
}

/**
 * Runs a command. Pass a generated wrapper (`() => commands.projectsList()`,
 * resolves to `{ status, data | error }`) or a command name and arguments
 * for the raw `invoke`, which rejects with the `CommandError` payload.
 */
export function call<T>(
  command: () => Promise<CommandResult<T>>
): Effect.Effect<T, BackendError>;
export function call<T>(
  command: string,
  args?: Record<string, unknown>
): Effect.Effect<T, BackendError>;
export function call<T>(
  command: string | (() => Promise<CommandResult<T>>),
  args?: Record<string, unknown>
): Effect.Effect<T, BackendError> {
  if (typeof command === "string") {
    return Effect.tryPromise({
      catch: toBackendError,
      try: () => tauriInvoke<T>(command, args),
    });
  }
  return Effect.tryPromise({ catch: toBackendError, try: command }).pipe(
    Effect.flatMap((result) =>
      result.status === "ok"
        ? Effect.succeed(result.data)
        : Effect.fail(toBackendError(result.error))
    )
  );
}

/** An event wrapper generated by tauri-specta (`events.dataChanged`). */
export interface EventSource<T> {
  listen: (handler: EventCallback<T>) => Promise<UnlistenFn>;
}

/**
 * Subscribes to an event; the stream emits its payloads. The listener is
 * registered when the stream starts and removed in its finalizer, so an
 * interrupted subscriber (an unmounted screen) stops receiving events.
 */
export function listen<T>(
  event: EventName | EventSource<T>
): Stream.Stream<T, BackendError> {
  const register = (handler: EventCallback<T>) =>
    typeof event === "string"
      ? tauriListen<T>(event, handler)
      : event.listen(handler);

  return Stream.callback<T, BackendError>((queue) =>
    Effect.acquireRelease(
      Effect.tryPromise({
        catch: toBackendError,
        try: () =>
          register((message) => {
            Queue.offerUnsafe(queue, message.payload);
          }),
      }),
      (unlisten) => Effect.sync(unlisten)
    )
  );
}
